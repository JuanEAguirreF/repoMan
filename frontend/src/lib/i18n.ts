export function detectLocale(): Locale {
  const language = navigator.language.toLowerCase();
  return language.startsWith("es") ? "es" : "en";
}

export function useI18n() {
  const locale = useMemo(detectLocale, []);
  const t = messages[locale];
  return { locale, t };
}
